"""
The consolidated shell.

This application accumulated thirty-one separate pages in the navigation
-- seven of them differing only in which file input they showed. That is
not a lot of capability, it is one capability spread thin, and it made a
small app feel unusable.

Three pages replace most of it:

    /add        one page for every kind of source
    /analyse    the local analysis tools, in tabs rather than scattered
    /toolkit    the standalone components, presented honestly as components

Nothing was deleted. The older routes still work and still have their
tests; they are simply no longer the way in.
"""
