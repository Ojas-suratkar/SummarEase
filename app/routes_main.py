@bp.get("/add")
@login_required
def add_source():
    """One page for every kind of source.

    Previously seven near-identical pages, which made the application
    look larger and more confusing than it is. The type selector changes
    one input; everything else on the page stays put.
    """
    return render_template(
        "add.html",
        source_types=SOURCE_TYPES,
        image_modes=IMAGE_MODES,
        preselected=request.args.get("kind", "text"),
    )


@bp.get("/analyse")
@login_required
def analyse():
    return render_template(
        "analyse.html",
        tabs=ANALYSIS_TABS,
        stats=entry_manager.library_stats(current_user.id),
    )


@bp.get("/toolkit")
@login_required
def toolkit():
    return render_template(
        "toolkit.html",
        components=TOOLKIT,
        storage=source_store.storage_usage(current_user.id),
    )
